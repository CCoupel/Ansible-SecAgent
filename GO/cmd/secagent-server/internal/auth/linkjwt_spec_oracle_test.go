//
// The same table (specLinkCases) is run against:
//   - the ORACLE (a small, correct verifier written here): it must pass every case — this proves the
//     cases themselves are right;
//   - three MUTANTS of the oracle ("aud not verified", "previous kid always accepted", "seq not
//     verified"): each must FAIL at least the cases named for it — this proves the cases bite;
//   - the REAL implementation (linkjwt_spec_test.go), once the dev wires it.

