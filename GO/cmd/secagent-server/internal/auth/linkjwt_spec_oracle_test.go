// ── oracle ───────────────────────────────────────────────────────────────────

type specMutant string

const (
	specNoMutant              specMutant = ""
	specMutAudIgnored         specMutant = "aud-not-verified"
	specMutPrevAlwaysOK       specMutant = "previous-kid-always-accepted"
	specMutSeqIgnored         specMutant = "seq-not-verified"
	specMutIssIgnored         specMutant = "iss-not-verified"
	specKidLen                           = 12
	specLegacyRoleRelay                  = "relay"
	specRoleChild                        = "relay-child"
	specRoleParent                       = "relay-parent"
	specRootID                           = "root"
	specChildID, specParentID            = "relay-x", "relay-p"
)

// every key ever generated by a case, by kid: what the "previous always accepted" mutant remembers
var (
	specAllKeysMu sync.Mutex
	specAllKeys   = map[string]ed25519.PublicKey{}
)

func specRefKid(pub ed25519.PublicKey) string {
	h := sha256.Sum256(pub)
	return base64.RawURLEncoding.EncodeToString(h[:specKidLen])
}

type specRevMsg struct {
	Seq     uint64         `json:"seq"`
	Entries []specRevEntry `json:"entries"`
	Sig     []byte         `json:"sig"`
}

type specKeysMsg struct {
	CurrentPub  []byte `json:"current_pub"`
	PreviousPub []byte `json:"previous_pub"`
	Seq         uint64 `json:"seq"`
	Sig         []byte `json:"sig"`
}

func specRevPayload(seq uint64, e []specRevEntry) []byte {
	b, _ := json.Marshal(struct {
		Seq     uint64         `json:"seq"`
		Entries []specRevEntry `json:"entries"`
	}{seq, e})
	return b
}

func specKeysPayload(newCur, prev ed25519.PublicKey, seq uint64) []byte {
	b, _ := json.Marshal(struct {
		C, P []byte
		S    uint64
	}{newCur, prev, seq})
	return b
}

// specOracle builds the reference implementation, optionally mutated.
func specOracle(m specMutant) *specLinkImpl {
	impl := &specLinkImpl{KidOf: specRefKid, Code: func(err error) string {
		for _, c := range []string{"jwt_missing_kid", "jwt_unknown_kid", "jwt_missing_aud", "jwt_wrong_aud", "jwt_wrong_issuer"} {
			if strings.Contains(err.Error(), c) {
				return c
			}
		}
		return err.Error()
	}}

	impl.VerifyToken = func(trust specLinkTrust, token string, want specLinkWant, now time.Time) (bool, error) {
		p := jwt.NewParser(jwt.WithValidMethods([]string{"EdDSA"}), jwt.WithTimeFunc(func() time.Time { return now }))
		claims := jwt.MapClaims{}
		_, err := p.ParseWithClaims(token, claims, func(t *jwt.Token) (interface{}, error) {
			kid, _ := t.Header["kid"].(string)
			if kid == "" {
				return nil, errors.New("jwt_missing_kid")
			}
			if m == specMutPrevAlwaysOK {
				specAllKeysMu.Lock()
				defer specAllKeysMu.Unlock()
				if pub, ok := specAllKeys[kid]; ok {
					return pub, nil
				}
				return nil, errors.New("jwt_unknown_kid")
			}
			if trust.Current != nil && kid == specRefKid(trust.Current) {
				return trust.Current, nil
			}
			if trust.Previous != nil && kid == specRefKid(trust.Previous) {
				return trust.Previous, nil
			}
			return nil, errors.New("jwt_unknown_kid")
		})
		if err != nil {
			return true, err
		}
		if claims["exp"] == nil {
			return true, errors.New("exp_required")
		}
		if s, _ := claims["jti"].(string); s == "" {
			return true, errors.New("jti_required")
		}
		if s, _ := claims["sub"].(string); s == "" {
			return true, errors.New("sub_required")
		}
		if m != specMutAudIgnored {
			if claims["aud"] == nil {
				return true, errors.New("jwt_missing_aud")
			}
			aud, err := claims.GetAudience()
			if err != nil || len(aud) != 1 || aud[0] != want.LocalID {
				return true, errors.New("jwt_wrong_aud")
			}
		}
		if m != specMutIssIgnored {
			if iss, _ := claims["iss"].(string); iss == "" || iss != want.RootID {
				return true, errors.New("jwt_wrong_issuer")
			}
		}
		if role, _ := claims["role"].(string); role != want.Role {
			return true, fmt.Errorf("role_refused: %q", role)
		}
		if jti, _ := claims["jti"].(string); trust.Blacklisted != nil && trust.Blacklisted(jti) {
			return true, errors.New("revoked")
		}
		return false, nil
	}

	impl.SignToken = func(priv ed25519.PrivateKey, iss, sub, aud, role string, ttl time.Duration) (string, string, error) {
		jti := fmt.Sprintf("jti-%d", time.Now().UnixNano())
		now := time.Now()
		tok := jwt.NewWithClaims(jwt.SigningMethodEdDSA, jwt.MapClaims{
			"iss": iss, "sub": sub, "aud": aud, "role": role, "jti": jti,
			"iat": now.Unix(), "exp": now.Add(ttl).Unix(),
		})
		tok.Header["kid"] = specRefKid(priv.Public().(ed25519.PublicKey))
		s, err := tok.SignedString(priv)
		return s, jti, err
	}

	impl.SignRevocations = func(priv ed25519.PrivateKey, seq uint64, e []specRevEntry) ([]byte, error) {
		return json.Marshal(specRevMsg{Seq: seq, Entries: e, Sig: ed25519.Sign(priv, specRevPayload(seq, e))})
	}
	impl.VerifyRevocations = func(trust specLinkTrust, msg []byte) (uint64, []specRevEntry, error) {
		var r specRevMsg
		if err := json.Unmarshal(msg, &r); err != nil {
			return 0, nil, err
		}
		if trust.Current == nil || !ed25519.Verify(trust.Current, specRevPayload(r.Seq, r.Entries), r.Sig) {
			return 0, nil, errors.New("bad_signature")
		}
		if m != specMutSeqIgnored && r.Seq <= trust.LastSeq {
			return 0, nil, errors.New("stale_seq")
		}
		return r.Seq, r.Entries, nil
	}

	impl.SignLinkKeys = func(oldPriv ed25519.PrivateKey, newCur, prev ed25519.PublicKey, seq uint64) ([]byte, error) {
		return json.Marshal(specKeysMsg{CurrentPub: newCur, PreviousPub: prev, Seq: seq, Sig: ed25519.Sign(oldPriv, specKeysPayload(newCur, prev, seq))})
	}
	impl.ApplyLinkKeys = func(trust specLinkTrust, msg []byte) (specLinkTrust, error) {
		var k specKeysMsg
		if err := json.Unmarshal(msg, &k); err != nil {
			return trust, err
		}
		if trust.Current == nil || !ed25519.PublicKey(k.PreviousPub).Equal(trust.Current) ||
			!ed25519.Verify(trust.Current, specKeysPayload(k.CurrentPub, k.PreviousPub, k.Seq), k.Sig) {
			return trust, errors.New("chain_broken")
		}
		if m != specMutSeqIgnored && k.Seq <= trust.LastSeq {
			return trust, errors.New("stale_seq")
		}
		out := trust
		out.Previous, out.Current, out.LastSeq = trust.Current, ed25519.PublicKey(k.CurrentPub), k.Seq
		return out, nil
	}
	return impl
}

// ── forging helpers (independent of the signer under test) ───────────────────

type specKey struct {
	pub  ed25519.PublicKey
	priv ed25519.PrivateKey
}

func specNewKey(t *testing.T) specKey {
	t.Helper()
	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	specAllKeysMu.Lock()
	specAllKeys[specRefKid(pub)] = pub
	specAllKeysMu.Unlock()
	return specKey{pub, priv}
}

var (
	specRSAOnce sync.Once
	specRSAKey  *rsa.PrivateKey
)

func specRSA(t *testing.T) *rsa.PrivateKey {
	specRSAOnce.Do(func() {
		k, err := rsa.GenerateKey(rand.Reader, 2048)
		if err != nil {
			t.Fatal(err)
		}
		specRSAKey = k
	})
	return specRSAKey
}

// specBaseClaims is a valid link token for the child→parent direction (role relay-child, sub X, aud P).
func specBaseClaims(jti string) jwt.MapClaims {
	now := time.Now()
	return jwt.MapClaims{
		"iss": specRootID, "sub": specChildID, "aud": specParentID, "role": specRoleChild,
		"jti": jti, "iat": now.Unix(), "exp": now.Add(time.Hour).Unix(),
	}
}

func specForge(t *testing.T, method jwt.SigningMethod, key any, kid any, c jwt.MapClaims) string {
	t.Helper()
	tok := jwt.NewWithClaims(method, c)
	if kid != nil {
		tok.Header["kid"] = kid
	}
	s, err := tok.SignedString(key)
	if err != nil {
		t.Fatalf("forge: %v", err)
	}
	return s
}

// ── conformance cases ────────────────────────────────────────────────────────

// specCase returns "" when the verifier behaves as specified, otherwise why not.
type specCase struct {
	Name string
	Run  func(t *testing.T, impl *specLinkImpl) string
}

type specVerdict struct {
	trust specLinkTrust
	tok   string
	want  specLinkWant
}

func (v specVerdict) ask(impl *specLinkImpl) (permanent bool, err error) {
	return impl.VerifyToken(v.trust, v.tok, v.want, time.Now())
}

func specAccept(impl *specLinkImpl, v specVerdict) string {
	if _, err := v.ask(impl); err != nil {
		return "must be accepted, refused: " + err.Error()
	}
	return ""
}

// specRefuseWithCode is specRefuse plus the stable refusal code (checked when the impl exposes Code).
func specRefuseWithCode(impl *specLinkImpl, v specVerdict, code string) string {
	_, err := v.ask(impl)
	if err == nil {
		return "must be refused, accepted"
	}
	if impl.Code != nil {
		if got := impl.Code(err); got != code {
			return fmt.Sprintf("refusal code %q, want %q (%v)", got, code, err)
		}
	}
	return ""
}

func specRefuse(impl *specLinkImpl, v specVerdict) string {
	if _, err := v.ask(impl); err == nil {
		return "must be refused, accepted"
	}
	return ""
}

func specRefusePermanent(impl *specLinkImpl, v specVerdict) string {
	permanent, err := v.ask(impl)
	if err == nil {
		return "must be refused, accepted"
	}
	if !permanent {
		return "the refusal must be permanent (the child must not retry): " + err.Error()
	}
	return ""
}

var childWant = specLinkWant{LocalID: specParentID, RootID: specRootID, Role: specRoleChild}

